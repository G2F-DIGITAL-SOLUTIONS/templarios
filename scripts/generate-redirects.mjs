#!/usr/bin/env node
/**
 * Generates permanent redirect outputs from `src/i18n/legacy-redirects.ts`.
 *
 * Outputs:
 *  - redirects.generated.mjs  → consumed by astro.config.mjs (static redirect pages)
 *  - public/_redirects        → Netlify / Cloudflare Pages (301 rules)
 *  - vercel.json              → Vercel `redirects` block (permanent: true)
 *
 * Run with `npm run redirects` (also runs automatically before `npm run build`).
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { legacyRedirects } = await import(resolve(root, 'src/i18n/legacy-redirects.ts'));

if (!Array.isArray(legacyRedirects) || legacyRedirects.length === 0) {
  throw new Error('legacyRedirects is empty — refusing to generate redirect files.');
}

const duplicates = legacyRedirects
  .map((rule) => rule.from)
  .filter((from, index, all) => all.indexOf(from) !== index);
if (duplicates.length > 0) {
  throw new Error(`Duplicate redirect sources: ${[...new Set(duplicates)].join(', ')}`);
}

// 1. Astro config map (path → destination, hash preserved by meta refresh).
const map = Object.fromEntries(legacyRedirects.map(({ from, to }) => [from, to]));
await writeFile(
  resolve(root, 'redirects.generated.mjs'),
  `// Generated by scripts/generate-redirects.mjs — do not edit by hand.\nexport default ${JSON.stringify(map, null, 2)};\n`,
  'utf8',
);

// 2. Netlify / Cloudflare Pages.
const redirectLines = legacyRedirects.map(({ from, to }) => `${from}  ${to}  301`);
await writeFile(
  resolve(root, 'public/_redirects'),
  `# Generated by scripts/generate-redirects.mjs — do not edit by hand.\n${redirectLines.join('\n')}\n`,
  'utf8',
);

// 3. Vercel: merge into the existing config, preserving headers.
const vercelPath = resolve(root, 'vercel.json');
const vercel = JSON.parse(await readFile(vercelPath, 'utf8'));
vercel.redirects = legacyRedirects.map(({ from, to }) => ({
  source: from,
  destination: to,
  permanent: true,
}));
await writeFile(vercelPath, `${JSON.stringify(vercel, null, 2)}\n`, 'utf8');

console.log(
  `redirects: ${legacyRedirects.length} rules written to redirects.generated.mjs, public/_redirects and vercel.json`,
);
